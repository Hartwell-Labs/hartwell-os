#!/usr/bin/env python3
"""Render the UI fonts into src/font.h as grayscale glyph atlases.

Antialiased coverage (0..255) so the framebuffer UI does not look like blocky
terminal art. Baseline-aligned cells, ASCII 32..126.
"""
import os

from PIL import Image, ImageDraw, ImageFont

FACES = [
    ("fb_body", "/usr/share/fonts/liberation/LiberationSans-Regular.ttf", 19),
    ("fb_bold", "/usr/share/fonts/liberation/LiberationSans-Bold.ttf", 19),
    ("fb_h1", "/usr/share/fonts/liberation/LiberationSans-Bold.ttf", 34),
    ("fb_mono", "/usr/share/fonts/liberation/LiberationMono-Regular.ttf", 19),
]

out = [
    "/* generated by tools/mkfont.py — do not edit */",
    "#ifndef HWO_FONT_H",
    "#define HWO_FONT_H",
    "typedef struct { unsigned char w, h, adv; unsigned int off; } Glyph;",
    "typedef struct { const Glyph *g; const unsigned char *px; unsigned char cell_h, asc; } Face;",
    "",
]

for name, path, size in FACES:
    font = ImageFont.truetype(path, size)
    asc, desc = font.getmetrics()
    cell_h = asc + desc
    glyphs = []
    blob = bytearray()
    for code in range(32, 127):
        ch = chr(code)
        adv = max(1, int(round(font.getlength(ch))))
        w = adv + 2
        img = Image.new("L", (w, cell_h), 0)
        if ch != " ":
            ImageDraw.Draw(img).text((0, asc), ch, font=font, fill=255, anchor="ls")
        data = img.tobytes()
        glyphs.append((w, cell_h, adv, len(blob)))
        blob += data
    out.append(f"static const unsigned char {name}_px[] = {{")
    for i in range(0, len(blob), 24):
        out.append(",".join(str(b) for b in blob[i : i + 24]) + ",")
    out.append("};")
    out.append(f"static const Glyph {name}_g[95] = {{")
    for w, h, adv, off in glyphs:
        out.append(f"{{{w},{h},{adv},{off}}},")
    out.append("};")
    out.append(f"static const Face {name} = {{ {name}_g, {name}_px, {cell_h}, {asc} }};")
    out.append("")

out.append("#endif")
dest = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "font.h")
with open(dest, "w") as fh:
    fh.write("\n".join(out) + "\n")
print(f"{dest}: {os.path.getsize(dest) / 1024:.0f} KB")
