/* Turn src/font.h into a font atlas the browser build can blit.
 * The C UI draws 8-bit coverage glyphs, so the web build uses the very same
 * bitmaps instead of a webfont: the demo is pixel-identical to the appliance.
 *
 *   node web/build-font.mjs > web/font.json
 */
import { readFileSync } from "node:fs";

/* 2x atlases: same faces rasterised at double size, so the browser build can
   draw a 2560x1600 frame and stay sharp on any panel. Regenerate with
   `python3 tools/mkfont.py --scale 2`. */
const HEADER = new URL("../src/font2x.h", import.meta.url);
const SUFFIX = "2x";
const src = readFileSync(HEADER, "utf8");

function grab(name) {
    const body = src.match(new RegExp(`static const (?:unsigned char|Glyph) ${name}\\[\\d*\\] = \\{([\\s\\S]*?)\\n\\};`));
    if (!body) throw new Error(`missing ${name}`);
    return body[1];
}

function face(name) {
    const px = [...grab(`${name}${SUFFIX}_px`).matchAll(/\d+/g)].map(Number);
    const glyphs = [...grab(`${name}${SUFFIX}_g`).matchAll(/\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}/g)]
        .map((m) => ({ w: +m[1], h: +m[2], adv: +m[3], off: +m[4] }));
    const meta = src.match(new RegExp(`static const Face ${name}${SUFFIX} = \\{[^}]*,\\s*(\\d+),\\s*(\\d+)\\s*\\};`));
    if (glyphs.length !== 95) throw new Error(`${name}: ${glyphs.length} glyphs`);
    for (const g of glyphs) {
        if (g.off + g.w * g.h > px.length) throw new Error(`${name}: glyph out of range`);
    }
    return {
        cell: +meta[1],
        asc: +meta[2],
        glyphs,
        px: Buffer.from(px).toString("base64"),
    };
}

const out = {
    note: "generated by web/build-font.mjs from src/font2x.h — do not edit",
    scale: 2,
    faces: {
        body: face("fb_body"),
        bold: face("fb_bold"),
        h1: face("fb_h1"),
        mono: face("fb_mono"),
    },
};
process.stdout.write(JSON.stringify(out));
